#!/usr/bin/env node
// Write docs/name-link-review.md from the name linker.
// The validator requires the committed file to match this output.
//   node scripts/names/link-review.mjs
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { auditNameLinks, foldPersonToken, loadNameLinkData } from './link.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');

function cell(s) {
  return String(s ?? '').replace(/\|/g, '/').replace(/\s+/g, ' ').trim();
}

function candidateCell(byId, ids) {
  return ids.map((id) => `${id} (${byId.get(id)?.title || id})`).join('; ');
}

// Chronology notes and name-form citations are our own citations. They repeat CFAH, PDF, EEBO, and the like.
// The unmatched list is the 1617 passages, plus summaries and descriptions, where a history's name can still lack a record.
const UNMATCHED_KINDS = new Set(['raleigh', 'prose']);
const PROSE_BOILER = new Set([
  'added', 'display', 'dated', 'taking', 'preparing', 'printed', 'named', 'undated', 'history', 'world',
  'book', 'part', 'chapter', 'section', 'table', 'chronology', 'chronological', 'generations', 'cory',
  'ancient', 'fragments', 'hodges', 'london', 'jones', 'jordan', 'cfah', 'pdf', 'osf', 'eebo', 'tcp',
  'sort', 'tier', 'pending', 'reference', 'intake', 'edition', 'page', 'pages', 'volume', 'cited',
  'source', 'sources', 'record', 'records', 'person', 'people', 'event', 'events', 'note', 'notes',
  'birth', 'death', 'reign', 'year', 'years', 'anno', 'mundi', 'bc', 'ad', 'am',
  'raleigh', 'ruler', 'rulers', 'dynasty', 'dynasties', 'appendix', 'dates', 'reigns', 'baseline',
  'son', 'sons', 'daughter', 'daughters', 'gen', 'wife', 'wives', 'brother', 'brothers', 'mother',
  'father', 'children', 'child', 'kings',
].map((w) => foldPersonToken(w)));

export function buildNameLinkReview(rootDir = root) {
  const data = loadNameLinkData(rootDir);
  const audit = auditNameLinks(data);
  const byId = audit.linker.byId;
  const lines = [];
  const ambigTokens = new Set(audit.ambiguous.map((row) => row.fold));
  const tubalCain = audit.tubal.filter((row) => row.personId === 'tubal-cain');
  const tubalJapheth = audit.tubal.filter((row) => row.personId === 'tubal');
  const unmatchedGroups = new Map();
  let unmatchedSkipped = 0;
  for (const row of audit.unmatched) {
    if (!UNMATCHED_KINDS.has(row.kind)) { unmatchedSkipped += 1; continue; }
    if (row.kind === 'prose' && PROSE_BOILER.has(row.fold)) { unmatchedSkipped += 1; continue; }
    let group = unmatchedGroups.get(row.fold);
    if (!group) {
      group = { fold: row.fold, count: 0, raws: new Map(), kinds: new Map(), example: row };
      unmatchedGroups.set(row.fold, group);
    }
    group.count += 1;
    group.raws.set(row.raw, (group.raws.get(row.raw) || 0) + 1);
    group.kinds.set(row.kind, (group.kinds.get(row.kind) || 0) + 1);
  }
  const unmatchedSorted = [...unmatchedGroups.values()].sort((a, b) => b.count - a.count || a.fold.localeCompare(b.fold));
  const preferredRaw = (group) => [...group.raws.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))[0][0];

  lines.push('# Name-link review');
  lines.push('');
  lines.push('Generated by `node scripts/names/link-review.mjs`. Do not edit this file by hand. `npm run validate` checks that it matches the linker.');
  lines.push('');
  lines.push('The Other people list links a whole name when one person record matches it. A token that matches more than one record stays unlinked unless the Tubal context rule or `data/name-link-overrides.json` selects one record. The linker does not guess.');
  lines.push('');
  lines.push('Tubal in a passage or note about Cain’s line resolves to Tubal-cain. Otherwise it resolves to Japheth’s son. Cain’s line means the unit is linked to, or uniquely mentions, Lamech the Cainite, Zillah, Adah, Naamah, Jubal, Jabal, or Cain, or is linked to Tubal-cain, or uniquely names him Tubalcain or Tubal-cain. A bare Lamech does not count, because two records share that name.');
  lines.push('');
  lines.push('## Counts');
  lines.push('');
  lines.push(`- Tubal resolved to Tubal-cain: ${tubalCain.length}`);
  lines.push(`- Tubal resolved to Japheth’s son: ${tubalJapheth.length}`);
  lines.push(`- Ambiguous tokens left unlinked: ${audit.ambiguous.length} occurrences, ${ambigTokens.size} distinct tokens`);
  lines.push(`- Names that match no record, in the 1617 passages and in summaries and descriptions: ${[...unmatchedGroups.values()].reduce((n, g) => n + g.count, 0)} occurrences, ${unmatchedGroups.size} distinct names`);
  lines.push(`- Capitalized words skipped as citation boilerplate or intake wording: ${unmatchedSkipped}`);
  lines.push(`- Overrides stored: ${(data.overrides.overrides || []).length}`);
  lines.push('');

  lines.push('## Tubal');
  lines.push('');
  lines.push('| Unit | Count | Printed | Record | Reason | Excerpt |');
  lines.push('|---|---|---|---|---|---|');
  const tubalGroups = new Map();
  for (const row of audit.tubal) {
    const key = `${row.unitId}\n${row.personId}`;
    let group = tubalGroups.get(key);
    if (!group) { group = { ...row, count: 0, raws: new Map() }; tubalGroups.set(key, group); }
    group.count += 1;
    group.raws.set(row.raw, (group.raws.get(row.raw) || 0) + 1);
  }
  const tubalRows = [...tubalGroups.values()].sort((a, b) => a.unitId.localeCompare(b.unitId) || a.raw.localeCompare(b.raw));
  for (const row of tubalRows) {
    const cite = data.passageById.get(row.unitId)?.citation;
    const unit = cite ? `${row.unitId} (${cite})` : row.unitId;
    const printed = [...row.raws.keys()].sort().join(', ');
    lines.push(`| ${cell(unit)} | ${row.count} | ${cell(printed)} | ${row.personId} | ${cell(row.reason)} | ${cell(row.excerpt)} |`);
  }
  if (!tubalRows.length) lines.push('| — | 0 | — | — | No Tubal token was found. | — |');
  lines.push('');

  lines.push('## Ambiguous tokens left unlinked');
  lines.push('');
  lines.push('Each row is one occurrence. Candidates are the person records whose title, alternate name, or Latin name form matches the token. Nothing in the context rules or the override file selected one of them.');
  lines.push('');
  const groups = new Map();
  for (const row of audit.ambiguous) {
    const key = `${row.fold}\n${row.candidates.join(',')}`;
    let group = groups.get(key);
    if (!group) {
      group = { fold: row.fold, candidates: row.candidates, reason: row.reason, rows: [] };
      groups.set(key, group);
    }
    group.rows.push(row);
  }
  const groupList = [...groups.values()].sort((a, b) => b.rows.length - a.rows.length || a.fold.localeCompare(b.fold));
  if (!groupList.length) lines.push('None.');
  for (const group of groupList) {
    lines.push(`### ${group.rows[0].raw}`);
    lines.push('');
    lines.push(`- Occurrences: ${group.rows.length}`);
    lines.push(`- Candidates: ${candidateCell(byId, group.candidates)}`);
    lines.push(`- Reason: ${group.reason}`);
    lines.push('');
    lines.push('| Unit | Count | Excerpt |');
    lines.push('|---|---|---|');
    const byUnit = new Map();
    for (const row of group.rows) {
      let item = byUnit.get(row.unitId);
      if (!item) { item = { ...row, count: 0 }; byUnit.set(row.unitId, item); }
      item.count += 1;
    }
    const rows = [...byUnit.values()].sort((a, b) => a.unitId.localeCompare(b.unitId));
    for (const row of rows) {
      const cite = data.passageById.get(row.unitId)?.citation;
      const unit = cite ? `${row.unitId} (${cite})` : row.unitId;
      lines.push(`| ${cell(unit)} | ${row.count} | ${cell(row.excerpt)} |`);
    }
    lines.push('');
  }

  lines.push('## Names in histories that match no record');
  lines.push('');
  lines.push('A name here is a capitalized word of at least three letters, not a function word and not a Roman numeral, that matched no person. Sentence-initial words are included, so the list is wider than personal names. Only the 1617 passages and the summaries and descriptions are listed. Chronology notes and name-form citations are omitted: they repeat our own citation wording. Intake words such as Added, Display, CFAH, and PDF are omitted from summaries and descriptions. `raleigh` is a passage. `prose` is a summary or description.');
  lines.push('');
  lines.push('| Name | Occurrences | Kinds | Example unit |');
  lines.push('|---|---|---|---|');
  for (const group of unmatchedSorted) {
    const kinds = [...group.kinds.entries()].sort((a, b) => a[0].localeCompare(b[0])).map(([k, n]) => `${k} ${n}`).join(', ');
    lines.push(`| ${cell(preferredRaw(group))} | ${group.count} | ${cell(kinds)} | ${cell(group.example.unitId)} |`);
  }
  if (!unmatchedSorted.length) lines.push('| — | 0 | — | — |');
  lines.push('');
  return { markdown: `${lines.join('\n')}\n`, problems: audit.problems, audit, data };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { markdown, problems } = buildNameLinkReview(root);
  const path = join(root, 'docs/name-link-review.md');
  writeFileSync(path, markdown);
  console.log(`Wrote ${path} (${markdown.length} bytes)`);
  if (problems.length) {
    console.error(problems.map((p) => `  - ${p}`).join('\n'));
    process.exit(1);
  }
}
