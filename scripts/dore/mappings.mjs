// 1–116, 121–123, 137–144, 146–152, 156–241. 145 is an Apocrypha file inside 137–152.
export function canonicalNumbers() {
  const nums = [];
  const add = (a, b) => { for (let n = a; n <= b; n++) nums.push(n); };
  add(1, 116);
  add(121, 123);
  add(137, 144);
  add(146, 152);
  add(156, 241);
  return nums;
}

export function mappingFor(number) {
  const m = DORE_MAPPINGS[number];
  if (!m) return null;
  return {
    scripture_ref: m.scripture_ref,
    records: m.records.map(([id, basis, ref]) => (ref ? { id, basis, ref } : { id, basis })),
  };
}
