// Writes data/cfah-coverage.md: checklist of every CFAH anchor point (published 1–61 and OSF), every CFAH-1
// Table 1 row and every CFAH king list / dynasty table, each with its record id(s) or the reason it is not recorded.
import { writeFileSync, existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { PUBLISHED, NONE_REASON, OSF_APS, OSF_NONE_REASON, TABLE1_ROWS } from './aplist.mjs';
import { INCONSISTENCIES } from './inconsistencies.mjs';

const yl = (y) => (y == null ? '—' : y < 0 ? `${-y} BC` : `AD ${y}`);
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|');

export function writeCoverage({ recs, sortChanges, DATA, createdBy: createdByPhase }) {
  // index every CFAH entry by AP number and Table 1 year
  const byAp = {}; const t1 = [];
  for (const { doc: d, dir } of Object.values(recs)) {
    if (d.type === 'location') continue;
    const slots = d.type === 'event' ? [['', d.chronologies]] : Object.entries(d.dates || {});
    for (const [slot, list] of slots) for (const e of list) {
      if (e.source !== 'cfah' || e.date == null) continue;
      const ref = `${dir === 'people' ? 'people/' : ''}${d.id}${slot ? `#${slot}` : ''}`;
      const ap = e.cfah_ap || (e.cfah_basis === 'anchor_point' && (e.citation || '').match(/(?:AP-|Anchor Point #)(\d+)/)?.[0].replace(/\D+/, 'AP-'));
      if (ap) (byAp[ap] ||= []).push({ ref, e, d });
      if (e.cfah_basis === 'table1_baseline') t1.push({ ref, e, d });
    }
  }
  const refs = (n) => (byAp[`AP-${n}`] || []).map((x) => `\`${x.ref}\`${x.e.cfah_preprint ? ' (preprint)' : ''}`);
  let md = `# CFAH coverage checklist

Generated by \`node scripts/cfah/import.mjs\` (do not edit by hand). Every CFAH anchor point (AP) number found in the published papers (ARJ CFAH-1 to 6) and in the OSF preprints, every row of CFAH-1 Table 1, and every king list or dynasty table in the CFAH papers, each with the record(s) that carry it, or the reason it is not recorded.

- Record ids: \`event-id\` = data/events/event-id.json; \`people/id#slot\` = a date slot (birth, death, reign) of data/people/id.json.
- Every CFAH entry with an AP number carries \`cfah_ap\`; OSF entries carry \`cfah_preprint: true\` and cite "OSF preprint". Source texts: /workspace/cfah-src (private copies, never committed).
- Sort tiers: CFAH AP (1) > CFAH-1 Table 1 (2) > Ussher–Jones (3) > Ussher (4); provisional (Generations) only when none of these exists. OSF preprint APs count as tier 1 (existing convention, open question A1 option 1).

`;
  // ---- published
  const pubMissing = [];
  md += `## 1. Published anchor points AP-1 to AP-61 (ARJ CFAH-1 to 6)\n\n| AP | Paper | Event (as named) | Date as printed | Record(s) |\n|---|---|---|---|---|\n`;
  for (const [n, paper, what, date] of PUBLISHED) {
    const r = refs(n).filter((x) => !/preprint/.test(x));
    if (!paper) { md += `| ${n} | — | — | — | not recorded: ${NONE_REASON[n]} |\n`; continue; }
    if (!r.length) pubMissing.push(n);
    md += `| ${n} | ${paper} | ${cell(what)} | ${cell(date)} | ${r.length ? r.join(', ') : '**NOT RECORDED**'} |\n`;
  }
  // ---- OSF
  const osfMissing = [];
  md += `\n## 2. OSF preprint anchor points (AP-62 and up; plus AP-82, 88–93 used earlier)\n\nOSF components inventoried in docs/cfah-osf-collation.md. All are preprints (not peer-reviewed in ARJ); records say so in the citation and carry \`cfah_preprint\`.\n\n| AP | OSF paper | Event (as named) | Date as printed | Record(s) |\n|---|---|---|---|---|\n`;
  for (const [n, src, what, date] of OSF_APS) {
    if (!src) { md += `| ${n} | — | — | — | not recorded: ${OSF_NONE_REASON} |\n`; continue; }
    const r = refs(n);
    if (!r.length) osfMissing.push(n);
    md += `| ${n} | ${src.replace(/-osf$/, '').toUpperCase()} | ${cell(what)} | ${cell(date)} | ${r.length ? r.join(', ') : '**NOT RECORDED**'} |\n`;
  }
  // ---- Table 1
  const t1Missing = [];
  md += `\n## 3. CFAH-1 Table 1 "Biblically derived dates from Ussher and Jones"\n\n| Year (BC) as printed | Event as printed | Record(s) with a Table 1 entry | Higher tier on the record |\n|---|---|---|---|\n`;
  for (const [yr, what] of TABLE1_ROWS) {
    const hits = t1.filter((x) => x.e.date.startsWith(`${yr} BC`));
    if (!hits.length) t1Missing.push(yr);
    const hi = hits.map((x) => { const a = (x.d.type === 'event' ? x.d.chronologies : x.d.dates[x.ref.split('#')[1]] || []).find((e) => e.source === 'cfah' && e.cfah_basis === 'anchor_point' && e.date); return a ? `${a.cfah_ap || 'AP'} ${a.date} (tier 1 applies)` : ''; }).filter(Boolean);
    md += `| ${yr} | ${cell(what)} | ${hits.length ? hits.map((x) => `\`${x.ref}\``).join(', ') : '**NOT RECORDED**'} | ${hi.join('; ') || '—'} |\n`;
  }
  // ---- king lists
  const klFile = join(DATA, 'king-lists.json');
  const klMissing = [];
  md += `\n## 4. King lists, dynasty tables and national epochs\n\n`;
  if (existsSync(klFile)) {
    const kl = JSON.parse(readFileSync(klFile, 'utf8'));
    md += `Stored in data/king-lists.json (rendered at /king-lists/). Person records exist only for rulers the CFAH text dates (reign start/end, death); kings known only by a regnal length are listed without a record.\n\n| List | Source | Rows | Rows linked to a person | Rows linked to an event | Rows with no record (reason) |\n|---|---|---|---|---|---|\n`;
    for (const l of kl.lists) {
      const rows = l.entries.length; const p = l.entries.filter((e) => e.person).length; const ev = l.entries.filter((e) => e.event).length;
      const none = l.entries.filter((e) => !e.person && !e.event);
      const why = [...new Set(none.map((e) => e.note || l.unrecorded_reason || 'no BC date printed for these rows'))].join(' ');
      md += `| ${cell(l.title)}${l.preprint ? ' *(OSF preprint)*' : ''} (\`${l.id}\`) | ${cell(l.citation_short)} | ${rows} | ${p} | ${ev} | ${none.length}${none.length ? `: ${cell(why)}` : ''} |\n`;
    }
    const osf = kl.lists.filter((l) => l.preprint);
    if (osf.length) {
      const ents = osf.flatMap((l) => l.entries); const ppl = new Set(ents.filter((e) => e.person).map((e) => e.person));
      const created = Object.values(recs).filter((r) => r.doc.type === 'person' && createdByPhase?.[r.doc.id] === 'phase5').length;
      md += `\nOSF per-king tables (phase 5): ${osf.length} tables, ${ents.length} rows; ${ents.filter((e) => e.person).length} rows carry a printed BC date and link to ${ppl.size} person records (${created} created by this phase, the rest existing records reused); ${ents.filter((e) => !e.person && !e.event).length} rows are listed without a record (regnal lengths only, groups, gaps or footnotes). Each linked row is a display-only \`paper_text\` reign entry marked \`cfah_preprint\`, citing the OSF file, version, table and page.\n`;
    }
    if (kl.not_recorded?.length) {
      md += `\nNot stored as lists:\n\n`;
      for (const x of kl.not_recorded) md += `- ${x}\n`;
    }
  } else { md += `**Pending (phase 3).**\n`; klMissing.push('all'); }
  // ---- sort changes
  const sc = Object.entries(sortChanges).sort((a, b) => (a[1].to.year ?? 0) - (b[1].to.year ?? 0));
  md += `\n## 5. Sort changes made by the CFAH pass (${sc.length})\n\nA new CFAH tier date displaced the record's previous sort (provisional Generations, Ussher–Jones, Ussher or a lower CFAH tier). Each record's sorting note says so too.\n\n| Record | Was | Now | By |\n|---|---|---|---|\n`;
  for (const [id, c] of sc) md += `| \`${id}\` | ${c.from.tier} ${yl(c.from.year)} | ${c.to.tier} ${yl(c.to.year)} | ${cell(c.by)} |\n`;
  // ---- inconsistencies
  md += `\n## 6. Internal CFAH inconsistencies found\n\nAlso appended to docs/OPEN-QUESTIONS-FOR-KEVIN.md.\n\n`;
  for (const [id, t, d] of INCONSISTENCIES) md += `- **${id}. ${t}.** ${d}\n`;
  // ---- summary
  md = md.replace('\n## 1.', `\n## Summary\n\n- Published APs 1–61: ${PUBLISHED.filter((x) => x[1]).length - pubMissing.length} of ${PUBLISHED.filter((x) => x[1]).length} numbers recorded${pubMissing.length ? `; not recorded: ${pubMissing.map((n) => `AP-${n}`).join(', ')}` : ''}. AP-37 does not exist in the papers.\n- OSF APs: ${OSF_APS.filter((x) => x[1]).length - osfMissing.length} of ${OSF_APS.filter((x) => x[1]).length} numbers found are recorded${osfMissing.length ? `; not yet recorded: ${osfMissing.map((n) => `AP-${n}`).join(', ')}` : ''}. Numbers never found: ${OSF_APS.filter((x) => !x[1]).map((x) => x[0]).join(', ')}.\n- CFAH-1 Table 1: ${TABLE1_ROWS.length - t1Missing.length} of ${TABLE1_ROWS.length} rows have a Table 1 entry${t1Missing.length ? `; missing: ${t1Missing.join(', ')}` : ''}.\n- Sort changes: ${sc.length}. Inconsistencies flagged: ${INCONSISTENCIES.length}.\n\n## 1.`);
  writeFileSync(join(DATA, 'cfah-coverage.md'), md);
}
